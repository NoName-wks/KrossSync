			return false
		end
		
		return KrossSyncService.KrossSyncs[StoreName]
	end
	
	local self={
		MaxRetryTime=nil,
		Store = DataStoreService:GetDataStore(StoreName),
		Map = MemoryStoreService:GetHashMap(StoreName),
		MapName = StoreName,
		DataTemplate = DataTemplate,
		MemoryTemplate = MemoryTemplate,
		ExpirationTime = NormalExpirationTime or 600,
		LastData = {},
		--
		IsGetting = {},
		IsSaving = {},
		----.signal----
		OnNewData = signal(), -- Passes the new wrapper when another server's memory change is detected
		OnGettingToggle = signal(), -- Passes whether a read is in progress (boolean)
		OnSavingToggle = signal(), -- Passes whether a write is in progress (boolean)
		-- TODO: Add an OnOverwrite signal that reports the affected store and key
	}

	self = setmetatable(self,KrossSync)::KrossSync<typeof(DataTemplate),typeof(MemoryTemplate)>

	OnNewKrossSync:Fire(self)
	KrossSyncService.KrossSyncs[StoreName] = self

	return self

end

